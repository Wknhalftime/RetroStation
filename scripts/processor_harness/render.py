"""Render one input file through a chain: Liquidsoap (authoritative for final values: it links
its own FFmpeg, 7.1 as of 2026-10-24) or standalone FFmpeg (8.0.1 on the desktop). A preset
tuned through the standalone back end can behave differently inside Liquidsoap, so every
result records both versions (``ffmpeg_version``, ``liquidsoap_version``).

The Liquidsoap back end wraps the chain file in a generated script that:
- defines ``param_float``, ``param_int``, ``param_bool`` and ``param_string`` (name, default)
  for the preset's ``[params]``, and ``gauge(name, getter)`` for values to log every frame,
  all before including the chain, which must define ``chain(s)``;
- writes 32-bit float WAV and the stream's MP3 (libmp3lame, 128k, 44.1 kHz, the encoder
  session.liq uses), so the codec round trip goes through the same encoder as the stream;
- runs on its own unsynced clock (``clock.assign_new(sync="none")``, src/libs/clock.liq line
  11), so a render runs faster than real time, and shuts down once both outputs stop.

CPU time is sampled every 20 ms while the process runs (psutil cannot read it after exit), so
a render can lose up to 20 ms of it.
"""

from __future__ import annotations

import json
import math
import os
import re
import string
import subprocess
import time
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

import psutil

from processor_harness.audio_io import read_wav
from processor_harness.presets import ParamValue

GAUGE_PREFIX = "HARNESS_GAUGE\t"
_FLOAT = r"-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?|-?inf|nan"
_GAUGE_LINE = re.compile(rf"^HARNESS_GAUGE\t({_FLOAT})\t([^\t,]+)\t({_FLOAT})$")
_CACHE_VARS = ("LIQ_CACHE_DIR", "LIQ_CACHE_USER_DIR", "LIQ_CACHE_SYSTEM_DIR")
_CPU_SAMPLE_S = 0.02
# A render gets this long per second of audio, plus startup (cold script cache ~5 s).
_TIMEOUT_PER_AUDIO_S = 5.0
_TIMEOUT_STARTUP_S = 120.0

_WRAPPER = """\
# Generated by the processor harness for one render; edits are overwritten.
settings.frame.audio.samplerate := 44100
harness_floats = [$floats]
harness_ints = [$ints]
harness_bools = [$bools]
harness_strings = [$strings]
def param_float(name, default) = list.assoc(default=default, name, harness_floats) end
def param_int(name, default) = list.assoc(default=default, name, harness_ints) end
def param_bool(name, default) = list.assoc(default=default, name, harness_bools) end
def param_string(name, default) = list.assoc(default=default, name, harness_strings) end
harness_gauges = ref([])
def gauge(name, getter) =
  harness_gauges := [...harness_gauges(), (name, getter)]
end
%include "$chain"
s = chain(once(single("$source")))
harness_frames = ref(0)
def harness_log() =
  t = float(harness_frames()) * frame.duration()
  def log_one(g) =
    let (name, getter) = g
    v = getter()
    print("HARNESS_GAUGE\\t#{t}\\t#{name}\\t#{v}")
  end
  list.iter(log_one, harness_gauges())
  harness_frames := harness_frames() + 1
end
s.on_frame(synchronous=true, harness_log)
harness_stopped = ref(0)
def harness_stop() =
  harness_stopped := harness_stopped() + 1
  if harness_stopped() == 2 then shutdown() end
end
wav = output.file(
  fallible=true, %ffmpeg(format="wav", %audio(codec="pcm_f32le")), "$wav", s
)
mp3 = output.file(
  fallible=true,
  %ffmpeg(format="mp3", %audio(codec="libmp3lame", b="128k", ar=44100)),
  "$mp3",
  s
)
wav.on_stop(synchronous=false, harness_stop)
mp3.on_stop(synchronous=false, harness_stop)
clock.assign_new(sync="none", [s])
"""


class RenderError(RuntimeError):
    """A render failed; the message carries what the tool printed."""


@dataclass(frozen=True)
class RenderRun:
    output: Path
    mp3: Path | None
    gauges: Path | None
    cpu_seconds: float
    audio_seconds: float


def fill_graph(graph: str, params: Mapping[str, ParamValue]) -> str:
    """The filtergraph with each ``$name`` replaced by its param value."""
    try:
        return string.Template(graph).substitute({k: str(v) for k, v in params.items()})
    except KeyError as missing:
        raise RenderError(f"filtergraph needs param {missing} that the preset lacks") from None


def _audio_seconds(path: Path) -> float:
    x, fs = read_wav(path)
    return len(x) / fs


def _run_timed(
    command: list[str], log: Path, env: Mapping[str, str] | None, timeout: float
) -> float:
    """Run to completion with stdout and stderr in ``log``; CPU seconds used."""
    with log.open("w", encoding="utf-8", errors="replace") as out:
        process = psutil.Popen(
            command, stdout=out, stderr=subprocess.STDOUT, env=dict(env) if env else None
        )
        cpu, deadline = 0.0, time.monotonic() + timeout
        while process.poll() is None:
            try:
                times = process.cpu_times()
                cpu = times.user + times.system
            except psutil.Error:
                pass
            if time.monotonic() > deadline:
                process.kill()
                raise RenderError(f"{command[0]} timed out after {timeout:.0f} s; log: {log}")
            time.sleep(_CPU_SAMPLE_S)
    if process.returncode != 0:
        tail = log.read_text(encoding="utf-8", errors="replace")[-4000:]
        raise RenderError(f"{command[0]} exited with {process.returncode}:\n{tail}")
    return cpu


def _save_cpu(output: Path, cpu: float) -> None:
    """The render's CPU time beside it, so a later run can reuse the render (reuse_run)."""
    output.with_suffix(".run.json").write_text(json.dumps({"cpu_seconds": cpu}), encoding="utf-8")


def reuse_run(output: Path, liquidsoap: bool) -> RenderRun | None:
    """A finished render rebuilt from its files, or None if its WAV is missing. Gauges are
    extracted again from the Liquidsoap log, so a fixed parser applies to old runs; without
    a CPU sidecar (renders from before it existed) the CPU time is nan."""
    if not output.is_file():
        return None
    sidecar = output.with_suffix(".run.json")
    cpu = math.nan
    if sidecar.is_file():
        cpu = float(json.loads(sidecar.read_text(encoding="utf-8"))["cpu_seconds"])
    mp3 = output.with_suffix(".mp3")
    log = output.with_suffix(".log")
    gauges = None
    if liquidsoap and log.is_file():
        gauges = output.with_suffix(".gauges.csv")
        _write_gauges(log, gauges)
    return RenderRun(
        output,
        mp3 if liquidsoap and mp3.is_file() else None,
        gauges,
        cpu,
        _audio_seconds(output),
    )


def render_ffmpeg(ffmpeg: Path, graph: str, source: Path, output: Path) -> RenderRun:
    """Render through a filtergraph (input ``[0:a]``, output ``[out]``) to 32-bit float WAV."""
    audio_s = _audio_seconds(source)
    command = [
        str(ffmpeg), "-hide_banner", "-nostats", "-y", "-i", str(source),
        "-filter_complex", graph, "-map", "[out]", "-c:a", "pcm_f32le", str(output),
    ]  # fmt: skip
    timeout = _TIMEOUT_STARTUP_S + _TIMEOUT_PER_AUDIO_S * audio_s
    cpu = _run_timed(command, output.with_suffix(".log"), None, timeout)
    _save_cpu(output, cpu)
    return RenderRun(output, None, None, cpu, audio_s)


def _liq_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _liq_params(params: Mapping[str, ParamValue]) -> dict[str, str]:
    def pairs(values: dict[str, str]) -> str:
        return ", ".join(f"({_liq_string(k)}, {v})" for k, v in values.items())

    floats, ints, bools, strings = {}, {}, {}, {}
    for name, value in params.items():
        if isinstance(value, bool):
            bools[name] = "true" if value else "false"
        elif isinstance(value, int):
            ints[name] = str(value)
        elif isinstance(value, float):
            floats[name] = repr(value)
        else:
            strings[name] = _liq_string(value)
    return {
        "floats": pairs(floats),
        "ints": pairs(ints),
        "bools": pairs(bools),
        "strings": pairs(strings),
    }


def _write_gauges(log: Path, csv: Path) -> None:
    rows = ["time_s,name,value"]
    for line in log.read_text(encoding="utf-8", errors="replace").splitlines():
        # Liquidsoap's own log shares stdout and can land inside a gauge line: keep whole ones.
        whole = _GAUGE_LINE.match(line)
        if whole:
            rows.append(",".join(whole.groups()))
    csv.write_text("\n".join(rows) + "\n", encoding="utf-8")


def render_liquidsoap(
    liquidsoap: Path,
    chain: Path,
    params: Mapping[str, ParamValue],
    source: Path,
    output: Path,
    cache_dir: Path,
) -> RenderRun:
    """Render through ``chain(s)`` from the chain file; writes WAV, MP3 and gauges CSV."""
    audio_s = _audio_seconds(source)
    mp3 = output.with_suffix(".mp3")
    script = output.with_suffix(".liq")
    script.write_text(
        string.Template(_WRAPPER).substitute(
            chain=chain.resolve().as_posix(),
            source=source.resolve().as_posix(),
            wav=output.resolve().as_posix(),
            mp3=mp3.resolve().as_posix(),
            **_liq_params(params),
        ),
        encoding="utf-8",
    )
    cache_dir.mkdir(parents=True, exist_ok=True)
    env = {**os.environ, **{v: str(cache_dir.resolve()) for v in _CACHE_VARS}}
    log = output.with_suffix(".log")
    timeout = _TIMEOUT_STARTUP_S + _TIMEOUT_PER_AUDIO_S * audio_s
    cpu = _run_timed([str(liquidsoap), str(script)], log, env, timeout)
    if not output.is_file() or not mp3.is_file():
        tail = log.read_text(encoding="utf-8", errors="replace")[-4000:]
        raise RenderError(f"liquidsoap wrote no output for {source}:\n{tail}")
    gauges = output.with_suffix(".gauges.csv")
    _write_gauges(log, gauges)
    _save_cpu(output, cpu)
    return RenderRun(output, mp3, gauges, cpu, audio_s)


def ffmpeg_version(ffmpeg: Path) -> str:
    """First line of ``ffmpeg -version`` plus its libavfilter version."""
    out = subprocess.run(
        [str(ffmpeg), "-hide_banner", "-version"],
        capture_output=True,
        encoding="utf-8",
        errors="replace",
        check=True,
    ).stdout
    first = out.splitlines()[0]
    build = " ".join(first.split()[:3])
    avfilter = re.search(r"libavfilter\s+([\d. /]+)", out)
    lib = avfilter.group(1).split("/")[0].replace(" ", "") if avfilter else "unknown"
    return f"{build} (libavfilter {lib})"


def liquidsoap_version(liquidsoap: Path) -> str:
    """``liquidsoap --version`` plus the FFmpeg libraries linked into the binary, read from
    the version strings libavcodec and libavformat embed (Liquidsoap reports neither)."""
    out = subprocess.run(
        [str(liquidsoap), "--version"],
        capture_output=True,
        encoding="utf-8",
        errors="replace",
        check=True,
    ).stdout
    data = liquidsoap.read_bytes()
    found = []
    for lib, tag in (
        ("libavcodec", rb"Lavc(\d+\.\d+\.\d+)"),
        ("libavformat", rb"Lavf(\d+\.\d+\.\d+)"),
    ):
        match = re.search(tag, data)
        found.append(f"{lib} {match.group(1).decode() if match else 'unknown'}")
    return f"{out.splitlines()[0].strip()} ({', '.join(found)})"
