"""Host capacity (R18, Lance 2026-10-27: re-measure on any host change, with one command,
``scripts/run_host_load.py``): stand-in listener sessions of a preset's chain, their frame load,
and the start-up cost of a tune-in.

A session is songs from a playlist through the preset's chain to the stream's encoder
(libmp3lame at the stream's bitrate, 44.1 kHz), in real time, as a listener's session runs. Per
tick it times the span from the MP3 output's start to the end of a trailing dummy output; about
0.4 ms of clock
bookkeeping per tick falls outside it (measured unsynced, 2026-10-27), and Liquidsoap's clock
steps in about 1 ms on Windows. Frame load is that span against the 20 ms frame; the pass mark
is a p99.9 under 50% (math item 14).

Sessions run as production's do (R18): in a job that pins them to the reserved cores at
above-normal priority, while the command itself keeps to the other cores.
"""

from __future__ import annotations

import os
import string
import subprocess
import tempfile
import threading
import time
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import numpy as np
import psutil

from processor_harness.codec import MP3_BITRATE
from processor_harness.presets import Preset
from processor_harness.render import liq_params

FRAME_MS = 20.0
_CACHE_VARS = ("LIQ_CACHE_DIR", "LIQ_CACHE_USER_DIR", "LIQ_CACHE_SYSTEM_DIR")
_ENGINE_ENV = ("PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP")
_SESSION = """\
# Generated by the processor harness: one stand-in listener session (host_load).
settings.frame.audio.samplerate := 44100
settings.log.stdout := false
settings.log.file := true
settings.log.file.path := environment.get("LOG")
harness_floats = [$floats]
harness_ints = [$ints]
harness_bools = [$bools]
harness_strings = [$strings]
def param_float(name, default) = list.assoc(default=default, name, harness_floats) end
def param_int(name, default) = list.assoc(default=default, name, harness_ints) end
def param_bool(name, default) = list.assoc(default=default, name, harness_bools) end
def param_string(name, default) = list.assoc(default=default, name, harness_strings) end
def gauge(name, getter) = ignore((name, getter)) end
%include "$chain"
warm = float_of_string(environment.get("WARM_S"))
run_s = float_of_string(environment.get("RUN_S"))
s = chain(playlist(mode="normal", reload_mode="never", environment.get("PLAYLIST")))
o = output.file(
  fallible=true,
  %ffmpeg(format="mp3", %audio(codec="libmp3lame", b="$bitrate", ar=44100)),
  environment.get("OUT"),
  s
)
z = output.dummy(fallible=true, s)
t0 = ref(0.)
spans = ref([])
started = ref(false)
o.on_frame(synchronous=true, before=true, fun () -> begin
  t0 := time.up()
  if not started() then started := true; print("READY") end
end)
z.on_frame(synchronous=true, before=false, fun () -> begin
  t = time.up()
  if t > warm then spans := [t - t0(), ...spans()] end
  if t > warm + run_s then
    file.write(
      data=string.concat(separator="\\n", list.map(fun (x) -> string(x * 1000.), spans())),
      environment.get("FRAMES")
    )
    shutdown()
  end
end)
"""


@dataclass(frozen=True)
class FrameLoad:
    """One session's ticks, as spans in ms."""

    ticks: int
    p50_ms: float
    p999_ms: float
    max_ms: float
    late: int  # ticks longer than a frame

    @property
    def p999_share(self) -> float:
        return self.p999_ms / FRAME_MS


def frame_load(spans_ms: Sequence[float]) -> FrameLoad:
    spans = np.asarray(spans_ms, dtype=np.float64)
    return FrameLoad(
        ticks=len(spans),
        p50_ms=float(np.percentile(spans, 50)),
        p999_ms=float(np.percentile(spans, 99.9)),
        max_ms=float(spans.max()),
        late=int((spans > FRAME_MS).sum()),
    )


def rotated(songs: Sequence[str], i: int) -> list[str]:
    """The playlist of session ``i``: the songs from the ``i``-th on, wrapping round."""
    k = i % len(songs)
    return [*songs[k:], *songs[:k]]


def write_session_script(preset: Preset, path: Path) -> Path:
    """The stand-in session for ``preset``'s chain (a Liquidsoap preset)."""
    if preset.chain is None:
        raise ValueError(f"{preset.source}: host load needs a Liquidsoap preset with a chain")
    text = string.Template(_SESSION).substitute(
        chain=preset.chain.as_posix(), bitrate=MP3_BITRATE, **liq_params(preset.params)
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def _env(cache: Path, **session: str) -> dict[str, str]:
    base = {k: os.environ[k] for k in _ENGINE_ENV if k in os.environ}
    return {**base, **{v: str(cache) for v in _CACHE_VARS}, **session}


def warm_cache(liquidsoap: Path, script: Path, cache: Path) -> None:
    """Type-check ``script`` into ``cache`` without running it, as the app does at start (D34)."""
    cache.mkdir(parents=True, exist_ok=True)
    subprocess.run([str(liquidsoap), "--cache-only", str(script)], env=_env(cache),
                   capture_output=True, check=True)  # fmt: skip


def _launch(liquidsoap: Path, script: Path, cache: Path, work: Path, songs: Sequence[str],
            i: int, warm_s: float, run_s: float) -> subprocess.Popen[str]:  # fmt: skip
    playlist = work / f"s{i}.m3u"
    playlist.write_text("\n".join(rotated(songs, i)) + "\n", encoding="utf-8")
    env = _env(cache, PLAYLIST=str(playlist), OUT=str(work / f"s{i}.mp3"),
               FRAMES=str(work / f"s{i}.frames"), LOG=str(work / f"s{i}.log"),
               WARM_S=str(warm_s), RUN_S=str(run_s))  # fmt: skip
    return subprocess.Popen([str(liquidsoap), str(script)], env=env, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, encoding="utf-8",
                            errors="replace")  # fmt: skip


def _cpu_s(process: psutil.Process) -> float:
    times = process.cpu_times()
    return float(times.user + times.system)


@dataclass(frozen=True)
class Startup:
    """CPU seconds and wall seconds from launch to the first frame, one per start."""

    cpu_s: tuple[float, ...]
    wall_s: tuple[float, ...]


def _start_once(liquidsoap: Path, script: Path, cache: Path, song: str) -> tuple[float, float]:
    with tempfile.TemporaryDirectory() as tmp:
        t0 = time.perf_counter()
        session = _launch(liquidsoap, script, cache, Path(tmp), [song], 0, 1e9, 1e9)
        process = psutil.Process(session.pid)
        assert session.stdout is not None
        try:
            for line in session.stdout:
                if line.startswith("READY"):
                    return _cpu_s(process), time.perf_counter() - t0
            raise RuntimeError(f"{script} exited before its first frame")
        finally:
            session.kill()
            session.wait()


def warm_starts(liquidsoap: Path, script: Path, song: str, work: Path, runs: int) -> Startup:
    """Tune-ins with the script cache warm, as production runs them (D34)."""
    cache = work / "cache-warm"
    warm_cache(liquidsoap, script, cache)
    starts = [_start_once(liquidsoap, script, cache, song) for _ in range(runs)]
    return Startup(tuple(c for c, _ in starts), tuple(w for _, w in starts))


def cold_starts(liquidsoap: Path, script: Path, song: str, work: Path, runs: int) -> Startup:
    """Tune-ins with an empty script cache each time (a changed script before the re-warm)."""
    starts = []
    for i in range(runs):
        cache = work / f"cache-cold-{i}"
        cache.mkdir(parents=True, exist_ok=True)
        starts.append(_start_once(liquidsoap, script, cache, song))
    return Startup(tuple(c for c, _ in starts), tuple(w for _, w in starts))


@dataclass(frozen=True)
class SessionsResult:
    """``sessions`` stand-in sessions at once: each one's CPU (share of one thread) and frame
    load, the machine's CPU, and the catch-up warnings they logged."""

    sessions: int
    cpu_per_session: tuple[float, ...]
    machine_cpu_pct: float
    loads: tuple[FrameLoad, ...]
    catchups: int

    @property
    def total_threads(self) -> float:
        return sum(self.cpu_per_session)


class _Job(Protocol):
    def assign(self, pid: int) -> None: ...
    def close(self) -> None: ...


def _pinning_job(cpus: Sequence[int]) -> _Job | None:
    """The job production puts its sessions in (R18), or None without CPUs to pin to."""
    if not cpus:
        return None
    from backend.playout.windows_job import ABOVE_NORMAL, KillOnCloseJob  # Windows only

    return KillOnCloseJob(cpus=cpus, priority_class=ABOVE_NORMAL)


def run_sessions(liquidsoap: Path, script: Path, songs: Sequence[Path], work: Path,
                 sessions: int, warm_s: float, run_s: float,
                 cpus: Sequence[int]) -> SessionsResult:  # fmt: skip
    """``sessions`` sessions at once on ``cpus`` (none: wherever Windows puts them), measured
    for ``run_s`` after ``warm_s`` of warm-up."""
    work.mkdir(parents=True, exist_ok=True)
    cache = work / "cache"
    warm_cache(liquidsoap, script, cache)
    names = [str(s) for s in songs]
    job = _pinning_job(cpus)
    launched = []
    first = time.perf_counter()
    for i in range(sessions):
        session = _launch(liquidsoap, script, cache, work, names, i, warm_s, run_s)
        if job is not None:
            job.assign(session.pid)
        launched.append(session)
        time.sleep(0.25)
    for session in launched:  # drain stdout so a full pipe never blocks a session
        threading.Thread(target=session.communicate, daemon=True).start()
    last = time.perf_counter()
    processes = [psutil.Process(s.pid) for s in launched]
    # The CPU window sits inside every session's measured run: after the last one's warm-up,
    # and before the first one's run ends (each counts from its own start, after its launch).
    time.sleep(max(0.0, last + warm_s + 0.5 - time.perf_counter()))
    psutil.cpu_percent(None)
    c0, t0 = [_cpu_s(p) for p in processes], time.perf_counter()
    time.sleep(max(0.5, first + warm_s + run_s - 0.5 - time.perf_counter()))
    c1, t1 = [_cpu_s(p) for p in processes], time.perf_counter()
    machine = psutil.cpu_percent(None)
    for session in launched:
        session.wait(timeout=run_s + 120)
    if job is not None:
        job.close()
    loads = []
    for i in range(sessions):
        spans = [float(v) for v in (work / f"s{i}.frames").read_text().split()]
        loads.append(frame_load(spans))
    catchups = sum(
        (work / f"s{i}.log").read_text(encoding="utf-8", errors="replace").count("must catchup")
        for i in range(sessions)
    )
    return SessionsResult(
        sessions=sessions,
        cpu_per_session=tuple((b - a) / (t1 - t0) for a, b in zip(c0, c1, strict=True)),
        machine_cpu_pct=machine,
        loads=tuple(loads),
        catchups=catchups,
    )
